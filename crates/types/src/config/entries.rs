//! A configuration as named values, the inverse of reading one from YAML.

use super::ChainConfig;
use crate::{Epoch, Hex};

/// One configuration value, as the spec's YAML files write it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ConfigValue {
    /// An integer, such as a count, an epoch, or an amount in Gwei.
    Number(u64),
    /// Text, such as a name, a hex version, or a decimal past 64 bits.
    Text(String),
    /// The blob limit schedule, as epoch and limit pairs.
    Schedule(Vec<(Epoch, u64)>),
}

